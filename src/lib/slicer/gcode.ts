/**
 * Lecture des commentaires d'en-tête / de fin d'un G-code Bambu Studio ou OrcaSlicer
 * (secours quand on n'a pas le .3mf).
 */
import { normalizeHex } from '../color';
import { parseDurationText, productHint } from './bambu';
import { SlicerParseError, type SlicedFile, type SlicerFilament } from './types';

function splitList(v: string | undefined): string[] {
  if (v === undefined) return [];
  const sep = v.includes(';') ? ';' : ',';
  return v.split(sep).map((x) => x.trim().replace(/^"|"$/g, ''));
}

const nums = (v: string | undefined) => splitList(v).map((x) => Number(x));

/**
 * @param text en-tête + fin du fichier (pas besoin du corps : l'UI ne lit que les premiers
 *             et derniers centaines de Ko).
 */
export function parseGcodeMeta(text: string): SlicedFile {
  const kv = new Map<string, string>();
  let slicer: string | null = null;
  for (const raw of text.split(/\r?\n/)) {
    if (!raw.startsWith(';')) continue;
    const line = raw.replace(/^;+\s*/, '');
    if (!slicer) {
      const gen = /^generated by\s+(\S+(?:\s+[\d.]+)?)/i.exec(line) ?? /^(BambuStudio\s+[\d.]+)/i.exec(line);
      if (gen) slicer = gen[1]!;
    }
    // Bambu : « model printing time: 1h 2m; total estimated time: 1h 5m »
    if (/total estimated time:/i.test(line)) {
      const t = /total estimated time:\s*([^;]+)/i.exec(line);
      if (t) kv.set('total estimated time', t[1]!.trim());
      continue;
    }
    const m = /^([^=:]+?)\s*[=:]\s*(.*)$/.exec(line);
    if (m && !kv.has(m[1]!.trim().toLowerCase())) kv.set(m[1]!.trim().toLowerCase(), m[2]!.trim());
  }

  const grams = nums(kv.get('filament used [g]') ?? kv.get('total filament weight [g]'));
  const lengthsMm = nums(kv.get('filament used [mm]') ?? kv.get('total filament length [mm]'));
  const types = splitList(kv.get('filament_type'));
  const colors = splitList(kv.get('filament_colour') ?? kv.get('extruder_colour'));
  const settingsIds = splitList(kv.get('filament_settings_id'));
  const totalG = Number(kv.get('total filament used [g]') ?? NaN);
  if (!grams.length && !Number.isFinite(totalG)) {
    throw new SlicerParseError(
      'Aucune information de consommation trouvée dans ce G-code (commentaires Bambu Studio / OrcaSlicer attendus).',
    );
  }
  const warnings: string[] = [];
  const count = Math.max(grams.length, lengthsMm.length, 1);
  let filaments: SlicerFilament[] = Array.from({ length: count }, (_, i) => ({
    id: i + 1,
    type: types[i] ?? types[0] ?? '',
    color: normalizeHex(colors[i]),
    usedG: Math.round((grams[i] ?? 0) * 100) / 100,
    usedM:
      lengthsMm[i] != null && Number.isFinite(lengthsMm[i]) ? Math.round(lengthsMm[i]! / 10) / 100 : null,
    settingsId: settingsIds[i] ?? null,
    productHint: productHint(settingsIds[i]),
  }));
  if (!grams.length && Number.isFinite(totalG)) {
    filaments = [{ ...filaments[0]!, usedG: totalG }];
    if (types.length > 1)
      warnings.push('Seul le poids total est indiqué : vérifie la répartition entre les filaments.');
  }
  if (grams.length === 1 && types.length > 1)
    warnings.push('Poids unique pour plusieurs filaments : vérifie la répartition.');
  const prediction =
    parseDurationText(kv.get('total estimated time')) ??
    parseDurationText(kv.get('estimated printing time (normal mode)')) ??
    parseDurationText(kv.get('model printing time'));
  return {
    source: 'gcode',
    slicer,
    sliced: true,
    plates: [
      {
        index: 1,
        name: null,
        predictionS: prediction,
        weightG: Math.round(filaments.reduce((a, f) => a + f.usedG, 0) * 100) / 100,
        filaments: filaments.filter((f) => f.usedG > 0),
      },
    ],
    warnings,
  };
}
